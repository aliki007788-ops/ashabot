async function main() {
  console.log('🌱 New market clusters seed ...');
  const central = await prisma.brain.findFirst({ where: { isCentral: true } });

  const clusterIds = {};
  for (const c of CLUSTERS) {
    const row = await prisma.cluster.upsert({ where: { slug: c.slug }, update: c, create: c });
    clusterIds[c.slug] = row.id;
  }
  const brainIds = {};
  for (const b of BRAINS) {
    const row = await prisma.brain.upsert({ where: { slug: b.slug }, update: b, create: b });
    brainIds[b.slug] = row.id;
  }

  let count = 0;
  for (const [clusterSlug, bots] of Object.entries(BOTS)) {
    for (const [slug, name, icon, description, systemPrompt, tools, isPremium] of bots) {
      const data = {
        name, icon, description, systemPrompt,
        tools: JSON.stringify(tools),
        isPremium, isActive: true, temperature: 0.6, maxTokens: 1024,
        model: 'gpt-4o-mini', clusterId: clusterIds[clusterSlug],
      };
      const bot = await prisma.bot.upsert({ where: { slug }, update: data, create: { ...data, slug } });
      const targets = [brainIds[`${clusterSlug}-brain`], central && central.id].filter(Boolean);
      for (const brainId of targets) {
        await prisma.botBrain.upsert({
          where: { botId_brainId: { botId: bot.id, brainId } },
          update: {}, create: { botId: bot.id, brainId },
        });
      }
      count++;
    }
  }
  console.log(`✅ ${CLUSTERS.length} خوشه، ${BRAINS.length} مغز، ${count} ربات`);
}

main().catch((e) => { console.error(e); process.exit(1); }).finally(() => prisma.$disconnect());
